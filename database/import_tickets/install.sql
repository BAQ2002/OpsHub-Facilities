-- Oracle 19c. Instalar uma vez, separadamente da importação.
-- Requer o schema OHFC existente. DDL causa commit implícito.
-- Controle de correspondência: nunca pressupor que Número = REQUEST.ID.
CREATE TABLE OHFC_IMPORT_TICKET (
    SOURCE_NAME VARCHAR2(100 CHAR) NOT NULL,
    LEGACY_ID VARCHAR2(100 CHAR) NOT NULL,
    ID_REQUEST NUMBER(10) NOT NULL,
    CONTENT_HASH VARCHAR2(64 CHAR) NOT NULL,
    TARGET_HASH VARCHAR2(64 CHAR) NOT NULL,
    CONSTRAINT PK_IMPORT_TICKET PRIMARY KEY (SOURCE_NAME, LEGACY_ID),
    CONSTRAINT UQ_IMPORT_TICKET_REQUEST UNIQUE (ID_REQUEST),
    CONSTRAINT FK_IMPORT_TICKET_REQUEST FOREIGN KEY (ID_REQUEST) REFERENCES OHFC_REQUEST(ID)
);

-- Cada versão aplicada preserva as colunas originais e as regras interpretadas.
CREATE TABLE OHFC_IMPORT_SNAPSHOT (
    ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    SOURCE_NAME VARCHAR2(100 CHAR) NOT NULL,
    LEGACY_ID VARCHAR2(100 CHAR) NOT NULL,
    ID_REQUEST NUMBER(10) NOT NULL,
    CONTENT_HASH VARCHAR2(64 CHAR) NOT NULL,
    PAYLOAD CLOB NOT NULL CHECK (PAYLOAD IS JSON),
    IMPORTED_DATE DATE DEFAULT CURRENT_DATE NOT NULL,
    CONSTRAINT PK_IMPORT_SNAPSHOT PRIMARY KEY (ID),
    CONSTRAINT FK_IMPORT_SNAPSHOT_REQUEST FOREIGN KEY (ID_REQUEST) REFERENCES OHFC_REQUEST(ID)
);
