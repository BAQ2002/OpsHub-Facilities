-- Oracle 19c: 23 tabelas sem schema proprietario explicito.
-- JSON usa CLOB com envelope {"value": ...}; booleanos usam NUMBER(1).
-- Execute em uma base vazia. DDL Oracle efetua commits implicitos.

-- 1. OHFC_SLA
CREATE TABLE OHFC_SLA
(
    ID          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NAME        VARCHAR2(100 CHAR),
    DESCRIPTION VARCHAR2(255 CHAR),
    DEADLINE    INTERVAL DAY(9) TO SECOND(6) NOT NULL,

    CONSTRAINT PK_SLA
        PRIMARY KEY (ID)
);

