-- 1. SERVICE_LEVEL_AGREEMENT
CREATE TABLE SERVICE_LEVEL_AGREEMENT
(
    ID          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NAME        VARCHAR(100),
    DESCRIPTION VARCHAR(255),
    DEADLINE    INTERVAL NOT NULL,

    CONSTRAINT PK_SLA PRIMARY KEY (ID)
);

-- 2. SERVICE_CATEGORY
CREATE TABLE SERVICE_CATEGORY
(
    ID   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR(100),

    CONSTRAINT PK_SERVICE_CATEGORY PRIMARY KEY (ID)
);

-- 3. SECTOR
CREATE TABLE SECTOR
(
    ID            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NAME          VARCHAR(100) NOT NULL,
    ACCESS_LEVELS INTEGER,

    CONSTRAINT PK_SECTOR PRIMARY KEY (ID)
);

-- 4. MEMBERSHIP
CREATE TABLE MEMBERSHIP
(
    ID           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_SECTOR    INTEGER,
    NAME         VARCHAR(300),
    EMAIL        VARCHAR(300),
    ACCESS_LEVEL INTEGER,

    CONSTRAINT PK_MEMBERSHIP PRIMARY KEY (ID),

    CONSTRAINT FK_MEMBERSHIP_SECTOR
        FOREIGN KEY (ID_SECTOR)
            REFERENCES SECTOR (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


