CREATE TABLE OHFC_REQUEST(
    ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_REQUEST_TYPE     NUMBER(10) NOT NULL,
    ID_MEMBERSHIP_REQUESTER NUMBER(10) NOT NULL,
    ID_MEMBERSHIP_RESPONDER NUMBER(10),
    ID_LOCATION         NUMBER(10) NOT NULL,
    ID_SERVICE_TYPE     NUMBER(10) NOT NULL,
    ID_REQUEST_STATUS   NUMBER(10) NOT NULL,
    CREATED_DATE        TIMESTAMP,
    AGREED_DATE         TIMESTAMP,
    STARTED_DATE        TIMESTAMP,
    FINISHED_DATE       TIMESTAMP,
    CANCELED_DATE       TIMESTAMP,
    DESCRIPTION         VARCHAR2(300 CHAR),

    CONSTRAINT PK_REQUEST
        PRIMARY KEY (ID),

    CONSTRAINT FK_REQUEST_REQUEST_TYPE
        FOREIGN KEY (ID_REQUEST_TYPE)
            REFERENCES OHFC_REQUEST_TYPE (ID),

    CONSTRAINT FK_REQUEST_STATUS
        FOREIGN KEY (ID_REQUEST_STATUS)
            REFERENCES OHFC_REQUEST_STATUS (ID),

    CONSTRAINT FK_REQUEST_MEMBERSHIP_REQUESTER
        FOREIGN KEY (ID_MEMBERSHIP_REQUESTER)
            REFERENCES OHFC_MEMBERSHIP (ID),

    CONSTRAINT FK_REQUEST_MEMBERSHIP_RESPONDER
        FOREIGN KEY (ID_MEMBERSHIP_RESPONDER)
            REFERENCES OHFC_MEMBERSHIP (ID),

    CONSTRAINT FK_REQUEST_LOCATION
        FOREIGN KEY (ID_LOCATION)
            REFERENCES OHFC_LOCATION (ID),

    CONSTRAINT FK_REQUEST_SERVICE_TYPE
        FOREIGN KEY (ID_SERVICE_TYPE)
            REFERENCES OHFC_SERVICE_TYPE (ID)
);
