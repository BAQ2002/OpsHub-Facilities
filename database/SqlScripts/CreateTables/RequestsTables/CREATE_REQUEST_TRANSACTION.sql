CREATE TABLE OHFC_REQUEST_TRANSACTION
(
    ID                            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_REQUEST                    NUMBER(10) NOT NULL,
    ID_MEMBERSHIP_REQUESTER           NUMBER(10) NOT NULL,
    ID_MEMBERSHIP_RESPONDER           NUMBER(10) NOT NULL,
    ID_REQUEST_TRANSACTION_STATUS NUMBER(10) NOT NULL,
    DESCRIPTION                   VARCHAR2(30 CHAR),

    CONSTRAINT PK_REQUEST_TRANSACTION
        PRIMARY KEY (ID),

    CONSTRAINT FK_REQUEST_TRANSACTION_REQUEST
        FOREIGN KEY (ID_REQUEST)
            REFERENCES OHFC_REQUEST (ID),

    CONSTRAINT FK_REQUEST_TRANSACTION_MEMBERSHIP_REQUESTER
        FOREIGN KEY (ID_MEMBERSHIP_REQUESTER)
            REFERENCES OHFC_MEMBERSHIP (ID),

    CONSTRAINT FK_REQUEST_TRANSACTION_MEMBERSHIP_RESPONDER
        FOREIGN KEY (ID_MEMBERSHIP_RESPONDER)
            REFERENCES OHFC_MEMBERSHIP (ID),

    CONSTRAINT FK_REQUEST_TRANSACTION_STATUS
        FOREIGN KEY (ID_REQUEST_TRANSACTION_STATUS)
            REFERENCES OHFC_REQUEST_TRANSACTION_STATUS (ID)
);
