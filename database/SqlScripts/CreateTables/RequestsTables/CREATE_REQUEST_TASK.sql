CREATE TABLE OHFC_REQUEST_TASK
(
    ID              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_REQUEST      NUMBER(10) NOT NULL,
    STARTED_DATE  TIMESTAMP,
    FINISHED_DATE   TIMESTAMP,
    DESCRIPTION     VARCHAR2(300 CHAR),

    CONSTRAINT PK_REQUEST_TASK
        PRIMARY KEY (ID),

    CONSTRAINT FK_REQUEST_TASK_REQUEST
        FOREIGN KEY (ID_REQUEST)
            REFERENCES OHFC_REQUEST (ID)
);
