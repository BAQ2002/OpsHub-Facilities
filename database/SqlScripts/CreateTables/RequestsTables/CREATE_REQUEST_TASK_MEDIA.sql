CREATE TABLE OHFC_REQUEST_TASK_MEDIA
(
    ID                  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_REQUEST_TASK     NUMBER(10) NOT NULL,
    CONTENT             BLOB NOT NULL,

    FILE_NAME           VARCHAR2(255 CHAR),
    MIME_TYPE           VARCHAR2(100 CHAR) NOT NULL,
    FILE_SIZE           NUMBER(10),

    CREATED_DATE        TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT PK_REQUEST_TASK_MEDIA
        PRIMARY KEY (ID),

    CONSTRAINT FK_REQUEST_TASK_MEDIA_REQUEST_TASK
        FOREIGN KEY (ID_REQUEST_TASK)
            REFERENCES OHFC_REQUEST_TASK (ID)
        ON DELETE CASCADE
);