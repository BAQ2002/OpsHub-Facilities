CREATE TABLE REQUEST_TASK_MEDIA
(
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_REQUEST_TASK     INTEGER NOT NULL,
    CONTENT             BYTEA NOT NULL,

    FILE_NAME           VARCHAR(255),
    FILE_SIZE           VARCHAR(100),

    CREATED_DATE        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_REQUEST_TASK_MEDIA
        PRIMARY KEY (ID),

    CONSTRAINT FK_REQUEST_TASK_MEDIA_REQUEST_TASK
        FOREIGN KEY (ID_REQUEST_TASK)
            REFERENCES REQUEST_TASK (ID)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);