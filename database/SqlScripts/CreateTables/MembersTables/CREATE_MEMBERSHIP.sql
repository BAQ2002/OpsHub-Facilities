CREATE TABLE MEMBERSHIP
(
    ID           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_SECTOR    INTEGER,
    NAME         VARCHAR(300),
    EMAIL        VARCHAR(300),
    ACCESS_LEVEL INTEGER,

    CONSTRAINT PK_MEMBERSHIP PRIMARY KEY (ID),

    CONSTRAINT FK_MEMBERSHIP_SECTOR
        FOREIGN KEY (ID_SECTOR)
            REFERENCES SECTOR (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);