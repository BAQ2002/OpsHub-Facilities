CREATE TABLE OHFC_MEMBERSHIP
(
    ID           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_SECTOR    NUMBER(10),
    NAME         VARCHAR2(300 CHAR),
    EMAIL        VARCHAR2(300 CHAR),
    ACCESS_LEVEL NUMBER(10),

    CONSTRAINT PK_MEMBERSHIP PRIMARY KEY (ID),

    CONSTRAINT FK_MEMBERSHIP_SECTOR
        FOREIGN KEY (ID_SECTOR)
            REFERENCES OHFC_SECTOR (ID)
);