CREATE TABLE OHFC_TASK_MEMBER_OCCURRENCE
(
    ID              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_REQUEST_TASK         NUMBER(10) NOT NULL,
    ID_MEMBERSHIP   NUMBER(10) NOT NULL,

    CONSTRAINT PK_TASK_MEMBER_OCCURRENCE
        PRIMARY KEY (ID),

    CONSTRAINT FK_TASK_MEMBER_OCCURRENCE_TASK
        FOREIGN KEY (ID_REQUEST_TASK)
            REFERENCES OHFC_REQUEST_TASK (ID),

    CONSTRAINT FK_TASK_MEMBER_OCCURRENCE_MEMBERSHIP
        FOREIGN KEY (ID_MEMBERSHIP)
            REFERENCES OHFC_MEMBERSHIP (ID)
);
