CREATE TABLE CHECKLIST_FIELD_VALUE
(
    ID                          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_CHECKLIST_FIELD_TYPE     INTEGER NOT NULL,
    ID_REQUEST_TASK_CHECKLIST   INTEGER NOT NULL,
    VALUE                       JSONB,

    CONSTRAINT PK_CHECKLIST_FIELD_VALUE
        PRIMARY KEY (ID),

    CONSTRAINT FK_CHECKLIST_FIELD_VALUE_FIELD_TYPE
        FOREIGN KEY (ID_CHECKLIST_FIELD_TYPE)
            REFERENCES CHECKLIST_FIELD_TYPE (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_CHECKLIST_FIELD_VALUE_TASK_CHECKLIST
        FOREIGN KEY (ID_REQUEST_TASK_CHECKLIST)
            REFERENCES REQUEST_TASK_CHECKLIST (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT UQ_CHECKLIST_FIELD_VALUE
        UNIQUE (
            ID_REQUEST_TASK_CHECKLIST,
            ID_CHECKLIST_FIELD_TYPE
        )
);