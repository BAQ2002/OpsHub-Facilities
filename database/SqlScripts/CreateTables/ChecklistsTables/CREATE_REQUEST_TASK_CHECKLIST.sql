CREATE TABLE OHFC_REQUEST_TASK_CHECKLIST
(
    ID                  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_CHECKLIST_TYPE   NUMBER(10) NOT NULL,
    ID_REQUEST_TASK     NUMBER(10) NOT NULL,
    CORPORATION         VARCHAR2(255 CHAR),
    EQUIPMENT_TAG       VARCHAR2(100 CHAR),
    EQUIPMENT_BRAND     VARCHAR2(255 CHAR),
    EQUIPMENT_MODEL     VARCHAR2(255 CHAR),
    RENTED_EQUIPMENT    NUMBER(1) CHECK (RENTED_EQUIPMENT IN (0, 1)),
    SERIAL_NUMBER       VARCHAR2(255 CHAR),
    PT_NUMBER           VARCHAR2(20 CHAR),

    CONSTRAINT PK_REQUEST_TASK_CHECKLIST
        PRIMARY KEY (ID),

    CONSTRAINT FK_REQUEST_TASK_CHECKLIST_CHECKLIST_TYPE
        FOREIGN KEY (ID_CHECKLIST_TYPE)
            REFERENCES OHFC_CHECKLIST_TYPE (ID),

    CONSTRAINT FK_REQUEST_TASK_CHECKLIST_REQUEST_TASK
        FOREIGN KEY (ID_REQUEST_TASK)
            REFERENCES OHFC_REQUEST_TASK (ID)
);
