CREATE TABLE CHECKLIST_FIELD_TYPE
(
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_CHECKLIST_TYPE   INTEGER NOT NULL,
    NAME                VARCHAR(255) NOT NULL,
    TYPE                VARCHAR(50) NOT NULL,
    OPTIONS             JSONB,
    REQUIRED            BOOLEAN NOT NULL DEFAULT FALSE,
    ACTIVE              BOOLEAN NOT NULL DEFAULT TRUE,
    DISPLAY_ORDER       INTEGER NOT NULL,

    CONSTRAINT PK_CHECKLIST_FIELD_TYPE
        PRIMARY KEY (ID),

    CONSTRAINT FK_CHECKLIST_FIELD_TYPE_CHECKLIST_TYPE
        FOREIGN KEY (ID_CHECKLIST_TYPE)
            REFERENCES CHECKLIST_TYPE (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);