CREATE TABLE REQUEST_TASK_CHECKLIST
(
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_CHECKLIST_TYPE   INTEGER NOT NULL,
    ID_REQUEST_TASK     INTEGER NOT NULL,
    CORPORATION         VARCHAR(255),
    EQUIPMENT_TAG       VARCHAR(100),
    EQUIPMENT_BRAND     VARCHAR(255),
    EQUIPMENT_MODEL     VARCHAR(255),
    RENTED_EQUIPMENT    BOOLEAN,
    SERIAL_NUMBER       VARCHAR(255),
    PT_NUMBER           VARCHAR(20),

    CONSTRAINT PK_REQUEST_TASK_CHECKLIST
        PRIMARY KEY (ID),

    CONSTRAINT FK_REQUEST_TASK_CHECKLIST_CHECKLIST_TYPE
        FOREIGN KEY (ID_CHECKLIST_TYPE)
            REFERENCES CHECKLIST_TYPE (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_REQUEST_TASK_CHECKLIST_REQUEST_TASK
        FOREIGN KEY (ID_REQUEST_TASK)
            REFERENCES REQUEST_TASK (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);
