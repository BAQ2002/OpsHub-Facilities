CREATE TABLE OHFC_SERVICE_FIELD_TYPE
(
    ID                  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_SERVICE_TYPE     NUMBER(10),
    NAME                VARCHAR2(100 CHAR),
    TYPE                VARCHAR2(50 CHAR),
    OPTIONS             CLOB CHECK (OPTIONS IS JSON),
    REQUIRED            NUMBER(1) CHECK (REQUIRED IN (0, 1)),
    ACTIVE              NUMBER(1) CHECK (ACTIVE IN (0, 1)),
    DISPLAY_ORDER       NUMBER(10),

    CONSTRAINT PK_SERVICE_FIELD_TYPE
        PRIMARY KEY (ID),

    CONSTRAINT FK_SERVICE_TYPE
        FOREIGN KEY (ID_SERVICE_TYPE)
            REFERENCES OHFC_SERVICE_TYPE (ID)
);
