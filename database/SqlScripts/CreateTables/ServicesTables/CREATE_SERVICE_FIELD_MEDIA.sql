CREATE TABLE OHFC_SERVICE_FIELD_MEDIA
(
    ID                      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_SERVICE_FIELD_TYPE   NUMBER(10) NOT NULL,
    ID_REQUEST              NUMBER(10) NOT NULL,
    CONTENT                 BLOB NOT NULL,

    -- Campos Metadados --
    FILE_NAME               VARCHAR2(255 CHAR),
    MIME_TYPE               VARCHAR2(100 CHAR) NOT NULL,
    FILE_SIZE               NUMBER(10),

    CREATED_DATE              TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT PK_SERVICE_FIELD_MEDIA
        PRIMARY KEY (ID),

    CONSTRAINT FK_SERVICE_FIELD_MEDIA_FIELD_TYPE
        FOREIGN KEY (ID_SERVICE_FIELD_TYPE)
            REFERENCES OHFC_SERVICE_FIELD_TYPE (ID),

    CONSTRAINT FK_SERVICE_FIELD_MEDIA_REQUEST
        FOREIGN KEY (ID_REQUEST)
            REFERENCES OHFC_REQUEST (ID)
        ON DELETE CASCADE
);