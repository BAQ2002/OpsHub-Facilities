CREATE TABLE SERVICE_FIELD_VALUE
(
    ID                      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_SERVICE_FIELD_TYPE   INTEGER NOT NULL,
    ID_REQUEST              INTEGER NOT NULL,
    VALUE                   JSONB,

    CONSTRAINT PK_SERVICE_FIELD_VALUE
        PRIMARY KEY (ID),

    CONSTRAINT FK_SERVICE_FIELD_VALUE_FIELD_TYPE
        FOREIGN KEY (ID_SERVICE_FIELD_TYPE)
            REFERENCES SERVICE_FIELD_TYPE (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_SERVICE_FIELD_VALUE_REQUEST
        FOREIGN KEY (ID_REQUEST)
            REFERENCES REQUEST (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);
