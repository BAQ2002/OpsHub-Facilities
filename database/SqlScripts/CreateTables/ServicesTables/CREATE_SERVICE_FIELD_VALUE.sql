CREATE TABLE OHFC_SERVICE_FIELD_VALUE
(
    ID                      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_SERVICE_FIELD_TYPE   NUMBER(10) NOT NULL,
    ID_REQUEST              NUMBER(10) NOT NULL,
    VALUE                   CLOB CHECK (VALUE IS JSON),

    CONSTRAINT PK_SERVICE_FIELD_VALUE
        PRIMARY KEY (ID),

    CONSTRAINT FK_SERVICE_FIELD_VALUE_FIELD_TYPE
        FOREIGN KEY (ID_SERVICE_FIELD_TYPE)
            REFERENCES OHFC_SERVICE_FIELD_TYPE (ID),

    CONSTRAINT FK_SERVICE_FIELD_VALUE_REQUEST
        FOREIGN KEY (ID_REQUEST)
            REFERENCES OHFC_REQUEST (ID)
);
