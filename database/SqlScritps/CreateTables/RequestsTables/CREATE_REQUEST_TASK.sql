CREATE TABLE HUBFACL.REQUEST_TASK
(
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_REQUEST      INTEGER NOT NULL,
    START_DATETIME  TIMESTAMP,
    STOP_DATETIME   TIMESTAMP,
    DESCRIPTION     VARCHAR(100),

    CONSTRAINT PK_REQUEST_TASK
        PRIMARY KEY (ID),

    CONSTRAINT FK_REQUEST_TASK_REQUEST
        FOREIGN KEY (ID_REQUEST)
            REFERENCES HUBFACL.HUBFACL.REQUEST (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);
