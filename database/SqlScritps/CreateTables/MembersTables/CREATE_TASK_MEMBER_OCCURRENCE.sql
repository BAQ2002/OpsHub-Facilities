CREATE TABLE HUBFACL.TASK_MEMBER_OCCURRENCE
(
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_TASK         INTEGER NOT NULL,
    ID_MEMBERSHIP   INTEGER NOT NULL,

    CONSTRAINT PK_TASK_MEMBER_OCCURRENCE
        PRIMARY KEY (ID),

    CONSTRAINT FK_TASK_MEMBER_OCCURRENCE_TASK
        FOREIGN KEY (ID_TASK)
            REFERENCES REQUEST_TASK (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_TASK_MEMBER_OCCURRENCE_MEMBERSHIP
        FOREIGN KEY (ID_MEMBERSHIP)
            REFERENCES MEMBERSHIP (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);
