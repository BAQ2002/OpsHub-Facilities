CREATE TABLE HUBFACL.ASSOC_MEMBERSHIP_SECTOR
(
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_MEMBER           INTEGER NOT NULL,
    ID_SECTOR_ASSOC     INTEGER NOT NULL,
    ACCESS_LEVEL        INTEGER,

    CONSTRAINT PK_ASSOC_MEMBERSHIP_SECTOR
        PRIMARY KEY (ID),

    CONSTRAINT FK_ASSOC_MEMBERSHIP_SECTOR_MEMBER
        FOREIGN KEY (ID_MEMBER)
            REFERENCES HUBFACL.MEMBERSHIP (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_ASSOC_MEMBERSHIP_SECTOR_SECTOR
        FOREIGN KEY (ID_SECTOR_ASSOC)
            REFERENCES HUBFACL.SECTOR (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);
