CREATE TABLE SERVICE_FIELD_TYPE
(
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_SERVICE_TYPE     INTEGER,
    NAME                VARCHAR(100),
    TYPE                VARCHAR(50),
    OPTIONS             JSONB,
    REQUIRED            BOOLEAN,
    ACTIVE              BOOLEAN,
    DISPLAY_ORDER       INTEGER,

    CONSTRAINT PK_SERVICE_FIELDS_TYPE
        PRIMARY KEY (ID)
);
