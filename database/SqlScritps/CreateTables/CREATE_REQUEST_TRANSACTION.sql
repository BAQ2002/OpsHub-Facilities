CREATE TABLE REQUEST_TRANSACTION
(
    ID                            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_REQUEST                    INTEGER NOT NULL,
    ID_MEMBER_REQUESTER           INTEGER NOT NULL,
    ID_MEMBER_RESPONDER           INTEGER NOT NULL,
    ID_REQUEST_TRANSACTION_STATUS INTEGER NOT NULL,
    DESCRIPTION                   VARCHAR(30),

    CONSTRAINT PK_REQUEST_TRANSACTION
        PRIMARY KEY (ID),

    CONSTRAINT FK_REQUEST_TRANSACTION_REQUEST
        FOREIGN KEY (ID_REQUEST)
            REFERENCES REQUEST (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_REQUEST_TRANSACTION_MEMBER_REQUESTER
        FOREIGN KEY (ID_MEMBER_REQUESTER)
            REFERENCES MEMBERSHIP (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_REQUEST_TRANSACTION_MEMBER_RESPONDER
        FOREIGN KEY (ID_MEMBER_RESPONDER)
            REFERENCES MEMBERSHIP (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_REQUEST_TRANSACTION_STATUS
        FOREIGN KEY (ID_REQUEST_TRANSACTION_STATUS)
            REFERENCES REQUEST_TRANSACTION_STATUS (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);
