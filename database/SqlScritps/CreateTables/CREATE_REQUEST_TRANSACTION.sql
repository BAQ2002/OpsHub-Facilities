CREATE TABLE REQUEST_TRANSACTION
(
    ID                            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_REQUEST                    INTEGER NOT NULL,
    ID_MEMBER_REQUESTER           INTEGER NOT NULL,
    ID_MEMBER_RESPONDER           INTEGER NOT NULL,
    ID_REQUEST_TRANSACTION_STATUS INTEGER NOT NULL,
    DESCRIPTION                   VARCHAR(30),

    CONSTRAINT PK_REQUEST_TRANSACTION
        PRIMARY KEY (ID),

    CONSTRAINT FK_REQUEST_TRANSACTION_STATUS
        FOREIGN KEY (ID_REQUEST_TRANSACTION_STATUS)
            REFERENCES REQUEST_TRANSACTION_STATUS (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);