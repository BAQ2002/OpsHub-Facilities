CREATE TABLE SERVICE_FIELD_MEDIA
(
    ID                      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_SERVICE_FIELD_TYPE   INTEGER NOT NULL,
    ID_REQUEST              INTEGER NOT NULL,
    CONTENT                 BYTEA NOT NULL,

    -- Campos Metadados --
    FILE_NAME               VARCHAR(255),
    MIME_TYPE               VARCHAR(100) NOT NULL,
    FILE_SIZE               INTEGER,
    
    CREATED_AT              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_SERVICE_FIELD_MEDIA
        PRIMARY KEY (ID),

    CONSTRAINT FK_SERVICE_FIELD_MEDIA_FIELD_TYPE
        FOREIGN KEY (ID_SERVICE_FIELD_TYPE)
            REFERENCES SERVICE_FIELD_TYPE (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT FK_SERVICE_FIELD_MEDIA_REQUEST
        FOREIGN KEY (ID_REQUEST)
            REFERENCES REQUEST (ID)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);