CREATE TABLE HUBFACL.LOCATION
(
    ID          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_REGION   INTEGER,
    NAME        VARCHAR(100),
    LOCATION_X  DECIMAL(10,8),
    LOCATION_Y  DECIMAL(11,8),

    CONSTRAINT PK_LOCATION PRIMARY KEY (ID),

    CONSTRAINT FK_LOCATION_REGION
        FOREIGN KEY (ID_REGION)
            REFERENCES HUBFACL.REGION (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);
