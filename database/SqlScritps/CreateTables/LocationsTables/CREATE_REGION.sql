CREATE TABLE HUBFACL.REGION
(
    ID           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ID_BUSINESS  INTEGER,
    NAME         VARCHAR(100),

    CONSTRAINT PK_REGION PRIMARY KEY (ID),

    CONSTRAINT FK_REGION_BUSINESS
        FOREIGN KEY (ID_BUSINESS)
            REFERENCES HUBFACL.BUSINESS (ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);
