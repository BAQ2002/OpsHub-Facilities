CREATE TABLE OHFC_CHECKLIST_TYPE
(
    ID              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NAME            VARCHAR2(255 CHAR) NOT NULL,
    DESCRIPTION     VARCHAR2(500 CHAR),
    VERSION         VARCHAR2(50 CHAR) NOT NULL,
    ACTIVE          NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVE IN (0, 1)),

    CONSTRAINT PK_CHECKLIST_TYPE
        PRIMARY KEY (ID),

    CONSTRAINT UQ_CHECKLIST_TYPE_NAME_VERSION
        UNIQUE (NAME, VERSION)
);
