CREATE TABLE OHFC_CHECKLIST_FIELD_TYPE
(
    ID                  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_CHECKLIST_TYPE   NUMBER(10) NOT NULL,
    NAME                VARCHAR2(255 CHAR) NOT NULL,
    TYPE                VARCHAR2(50 CHAR) NOT NULL,
    OPTIONS             CLOB CHECK (OPTIONS IS JSON),
    REQUIRED            NUMBER(1) DEFAULT 0 NOT NULL CHECK (REQUIRED IN (0, 1)),
    ACTIVE              NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVE IN (0, 1)),
    DISPLAY_ORDER       NUMBER(10) NOT NULL,

    CONSTRAINT PK_CHECKLIST_FIELD_TYPE
        PRIMARY KEY (ID),

    CONSTRAINT FK_CHECKLIST_FIELD_TYPE_CHECKLIST_TYPE
        FOREIGN KEY (ID_CHECKLIST_TYPE)
            REFERENCES OHFC_CHECKLIST_TYPE (ID)
);