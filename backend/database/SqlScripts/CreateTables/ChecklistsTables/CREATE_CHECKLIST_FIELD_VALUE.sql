CREATE TABLE OHFC_CHECKLIST_FIELD_VALUE
(
    ID                          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_CHECKLIST_FIELD_TYPE     NUMBER(10) NOT NULL,
    ID_REQUEST_TASK_CHECKLIST   NUMBER(10) NOT NULL,
    VALUE                       CLOB CHECK (VALUE IS JSON),

    CONSTRAINT PK_CHECKLIST_FIELD_VALUE
        PRIMARY KEY (ID),

    CONSTRAINT FK_CHECKLIST_FIELD_VALUE_FIELD_TYPE
        FOREIGN KEY (ID_CHECKLIST_FIELD_TYPE)
            REFERENCES OHFC_CHECKLIST_FIELD_TYPE (ID),

    CONSTRAINT FK_CHECKLIST_FIELD_VALUE_TASK_CHECKLIST
        FOREIGN KEY (ID_REQUEST_TASK_CHECKLIST)
            REFERENCES OHFC_REQUEST_TASK_CHECKLIST (ID),

    CONSTRAINT UQ_CHECKLIST_FIELD_VALUE
        UNIQUE (
            ID_REQUEST_TASK_CHECKLIST,
            ID_CHECKLIST_FIELD_TYPE
        )
);